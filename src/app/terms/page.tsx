import type { Metadata } from "next";
import { LegalShell } from "@/components/site/LegalShell";
import { getAppSettings } from "@/lib/db";
import { formatRub } from "@/lib/format";

export const dynamic = "force-dynamic";

export const metadata: Metadata = {
  title: "Условия заказа",
  description:
    "Как в демо-кафе «Тёплый бокс» согласуются цена и время, что значит «по запросу», как работают доставка, отмена и бонусы.",
  alternates: { canonical: "/terms" },
};

export default async function TermsPage() {
  const settings = await getAppSettings();
  const { company, pricing, game } = settings;
  return (
    <LegalShell
      company={company}
      title="Условия заказа"
      meta="Это демонстрационные условия для учебного проекта. Они не являются публичной офертой."
    >
      <section>
        <h2>1. Как устроен заказ</h2>
        <p>
          Сайт помогает собрать заказ и отправить заявку. После отправки заказ получает статус
          «Новый». Владелец проверяет состав, связывается с вами, подтверждает итоговую цену и
          время. До подтверждения заказ не считается принятым к производству.
        </p>
      </section>

      <section>
        <h2>2. Цены и минимум</h2>
        <p>
          Цены в меню указаны в рублях. Минимум заказа — {formatRub(pricing.minOrder)} по блюдам
          с известной ценой. Доставка по городу — {formatRub(pricing.deliveryFee)}, выезд за
          город — {formatRub(pricing.outOfTownFee)}. Доставка и выезд добавляются отдельно и не
          входят в минимум.
        </p>
        <p>
          Двойная начинка добавляет {pricing.doublePercent}% к базовой цене варианта, второй соус —{" "}
          {pricing.secondSaucePercent}%. Каждая надбавка округляется до целого рубля. Итог всегда
          пересчитывает сервер, а не браузер.
        </p>
      </section>

      <section>
        <h2>3. «Своё блюдо» и цена по запросу</h2>
        <p>
          Для своей позиции нужны описание и хотя бы одно фото. Такая позиция не имеет известной
          цены, не участвует в минимуме и не показывается как бесплатная. Стоимость согласуется
          отдельно; в заказе она отображается как «по запросу».
        </p>
      </section>

      <section>
        <h2>4. Доставка и самовывоз</h2>
        <p>
          Доставка доступна в пределах зоны «{company.deliveryArea}». Для доставки нужен адрес:
          улица, дом и квартира. Самовывоз — по адресу {company.address}. Время работы:{" "}
          {company.workingHours}. Если указано время, обязательно указывается дата; иначе заказ
          считается заказом «как можно скорее».
        </p>
      </section>

      <section>
        <h2>5. Отмена и изменение</h2>
        <p>
          Пока заказ в статусе «Новый», его можно отменить, написав владельцу. После подтверждения
          и начала приготовления отмена зависит от готовности блюд. В демо-проекте оплата не
          подключена, поэтому возвратов нет.
        </p>
      </section>

      <section>
        <h2>6. Игра и бонусы</h2>
        <p>
          {game.mode === "off"
            ? "Игра и бонусы сейчас выключены."
            : game.mode === "play"
              ? "Игра доступна после выполнения заказа, бонус за неё не начисляется."
              : `После выполнения заказа доступна игра. За прохождение выдаётся один код на ${formatRub(game.bonusAmount)} для следующего заказа от ${formatRub(game.bonusMinOrder)}, срок действия — ${game.bonusDays} дн.`}{" "}
          Код не применяется к текущему заказу, не суммируется с другими кодами и активируется
          только вручную в кабинете владельца. Один заказ — один код.
        </p>
      </section>

      <section>
        <h2>7. Ограничения демо</h2>
        <p>
          Проект не подключён к платёжному провайдеру, картам и реальной кухне. Контакты и адрес
          вымышлены. Мы не гарантируем доставку еды и не принимаем реальные платежи. Проверка
          честности прохождения игры выполняется на стороне клиента — это осознанное ограничение.
        </p>
      </section>

      <section>
        <h2>8. Контакты</h2>
        <p>
          Вопросы по заказу: <a href={`mailto:${company.email}`}>{company.email}</a>
          {company.phone ? (
            <>
              , телефон <a href={`tel:${company.phone.replace(/[^+\d]/g, "")}`}>{company.phone}</a>
            </>
          ) : null}
          .
        </p>
        <p className="legal-meta">Обновлено: 12 ноября 2026 года.</p>
      </section>
    </LegalShell>
  );
}
